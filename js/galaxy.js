/* =========================================================
   galaxy.js — 우리은하 계산 엔진
   ---------------------------------------------------------
   이 파일은 화면을 전혀 모른다. 숫자와 자료만 만든다.
   (앞선 다섯 앱의 엔진과 같은 역할 · 같은 규칙)

   ⚠ ES 모듈(import/export)을 쓰지 않는다. 더블클릭(file://)으로도 열려야 한다.

   ---------------------------------------------------------
   엔진의 핵심 아이디어 — 여기를 고칠 사람은 반드시 읽을 것
   ---------------------------------------------------------

   1. **은하수가 띠로 보이는 이유를 '별의 겹침'으로 계산한다**

      선생님 학습지의 물음 세 가지가 모두 여기서 나온다 —
        · 은하수가 띠 모양으로 보이는 이유는?
        · 은하수의 폭과 밝기는 일정할까? 이유는?
        · 왜 여름철에 더 잘 보일까?

      말로 답하면 외울 것이 되지만, **우리가 원반 안에 있다**는 사실 하나로 셋 다 풀린다.
      그래서 이 엔진은 관측 방향(은하 중심에서 몇 도 떨어진 쪽을 보는가)마다
      **시선이 원반을 얼마나 길게 통과하는지**를 계산한다.
        · 원반을 따라 보면 → 통과 거리가 길다 → 별이 많이 겹친다 → **밝다**
        · 원반 위아래로 보면 → 금방 원반을 벗어난다 → **어둡다**
      그래서 하늘에 **띠**로 보이고, 중심 쪽이 가장 밝고 두껍다.
      여름 밤에는 지구의 밤 방향이 **은하 중심 쪽**을 향해서 더 잘 보인다.

   2. 우리은하의 수치는 **선생님 학습지 그대로**

      지름 약 30000 pc · 태양계는 중심에서 약 8500 pc · 별 약 2000억 개 · 막대나선은하.
      **'더 최신 값'으로 고치지 말 것** — 학생이 종이와 화면을 나란히 놓고 본다.

   3. 성단·성운은 **짝지어 비교할 수 있게** 자료를 담는다

      산개 ↔ 구상, 방출 ↔ 반사 ↔ 암흑.
      학생이 헷갈리는 것은 개별 사실이 아니라 **무엇과 무엇이 짝인가**이므로,
      같은 항목(별 수 · 모양 · 색 · 있는 곳)을 모두 채워 나란히 놓는다.
   ========================================================= */
(function (global) {
  "use strict";

  function clamp(v, lo, hi) { return v < lo ? lo : (v > hi ? hi : v); }

  /* ---------------------------------------------------------
     1. 우리은하의 크기 (선생님 학습지 값)
     --------------------------------------------------------- */
  var MW = {
    kind: "막대나선은하",
    stars: 2000,             // 억 개
    diameterPc: 30000,       // 지름 (pc)
    sunFromCenterPc: 8500,   // 태양계가 중심에서 떨어진 거리 (pc)
    thicknessPc: 1000,       // 원반의 두께 (pc) — 띠로 보이는 까닭을 계산할 때 쓴다
    bulgePc: 4000            // 중심부(팽대부)의 지름 (pc)
  };
  var LY_PER_PC = 3.26;

  function pcToLy(pc) { return pc * LY_PER_PC; }

  /* ---------------------------------------------------------
     2. 은하수 — 시선이 원반을 얼마나 길게 통과하는가
        b : 은하면에서 위아래로 벌어진 각 (도). 0이면 원반을 따라 보는 것.
        l : 은하 중심에서 좌우로 벌어진 각 (도). 0이면 중심 쪽.
     --------------------------------------------------------- */

  /* 원반을 따라 볼 때(=은하면 위) 시선이 원반 안에 머무는 거리(pc).
     태양은 중심에서 8500 pc 떨어져 있으므로, 중심 쪽을 보면 길고 바깥쪽을 보면 짧다. */
  function pathInDisk(lDeg, bDeg) {
    var R = MW.diameterPc / 2;              // 원반 반지름
    var d = MW.sunFromCenterPc;
    var l = lDeg * Math.PI / 180;

    /* 태양에서 각 l 로 뻗은 시선이 반지름 R 인 원반을 벗어날 때까지의 거리 */
    var cos = Math.cos(l);
    var inside = R * R - d * d * (1 - cos * cos);
    if (inside < 0) return 0;
    var s = d * cos + Math.sqrt(inside);    // 원반 가장자리까지의 거리

    /* 은하면에서 b 만큼 벗어나 보면, 두께 안에 머무는 거리로 잘린다 */
    var b = Math.abs(bDeg) * Math.PI / 180;
    if (b > 1e-6) {
      var maxAlongPlane = (MW.thicknessPc / 2) / Math.tan(b);
      s = Math.min(s, maxAlongPlane);
    }
    return Math.max(s, 0);
  }

  /* 그 방향의 밝기(상댓값 0~1). 통과 거리가 길수록 별이 많이 겹쳐 밝다.
     중심부(팽대부)를 지나면 별이 더 빽빽하므로 조금 더 밝게 잡는다. */
  function milkyBrightness(lDeg, bDeg) {
    var s = pathInDisk(lDeg, bDeg);
    var maxS = MW.sunFromCenterPc + MW.diameterPc / 2;     // 가장 길게 통과할 때
    var base = clamp(s / maxS, 0, 1);
    /* 중심 쪽(l 이 작을수록)은 팽대부까지 겹쳐 더 밝다 */
    var toward = Math.cos(clamp(Math.abs(lDeg), 0, 180) * Math.PI / 180);
    var bulge = clamp((toward + 1) / 2, 0, 1) * 0.45;
    return clamp(base * 0.75 + bulge * base, 0, 1);
  }

  /* ---------------------------------------------------------
     3. 성단 — 산개 ↔ 구상 (선생님 학습지의 표 그대로)
     --------------------------------------------------------- */
  var CLUSTERS = [
    {
      key: "open", name: "산개 성단",
      count: "수십 개 ~ 수만 개",
      shape: "일정한 모양 없이 엉성하게",
      color: "푸른색", css: "#9db4ff",
      where: "우리은하의 나선팔",
      examples: ["M11", "프레세페 성단", "플레이아데스 성단"]
    },
    {
      key: "globular", name: "구상 성단",
      count: "수만 개 ~ 수십만 개",
      shape: "공 모양으로 빽빽하게",
      color: "붉은색", css: "#ff9b6b",
      where: "우리은하의 중심부와 은하 원반을 둘러싼 구형의 공간",
      examples: ["M3 (NGC 5272)", "M13 (NGC 6205)", "NGC 7089"]
    }
  ];

  /* ---------------------------------------------------------
     4. 성간 물질과 성운 — 방출 ↔ 반사 ↔ 암흑
     --------------------------------------------------------- */
  var NEBULAE = [
    {
      key: "emission", name: "방출 성운",
      how: "성간 물질이 주변의 별빛을 <b>흡수하여 가열</b>되면서 스스로 빛을 낸다",
      color: "붉은색", css: "#ff6b6b",
      examples: ["삼렬 성운", "장미 성운"]
    },
    {
      key: "reflection", name: "반사 성운",
      how: "성간 물질이 주변의 <b>별빛을 반사</b>한다",
      color: "푸른색", css: "#6ba8ff",
      examples: ["IC 2613", "M78", "IC 2118"]
    },
    {
      key: "dark", name: "암흑 성운",
      how: "성간 물질이 <b>뒤쪽에서 오는 별빛을 가로막는다</b>",
      color: "검은색", css: "#3b3b46",
      examples: ["말머리 성운", "뱀 성운", "버나드 68"]
    }
  ];

  function byKey(list, k) {
    for (var i = 0; i < list.length; i++) if (list[i].key === k) return list[i];
    return list[0];
  }

  /* ---------------------------------------------------------
     5. 계절과 은하 중심 방향
        여름 밤에는 지구의 밤 쪽이 은하 중심(궁수자리 방향)을 향한다.
        겨울 밤에는 그 반대쪽(바깥쪽)을 향해 은하수가 옅다.
        각도는 '중심에서 몇 도 떨어진 쪽을 보는가'를 뜻한다.
     --------------------------------------------------------- */
  var SEASONS = [
    { key: "summer", name: "여름", lDeg: 0,   note: "밤하늘이 은하 <b>중심 쪽</b>을 향한다" },
    { key: "spring", name: "봄",   lDeg: 90,  note: "은하면을 <b>옆으로</b> 보는 쪽" },
    { key: "autumn", name: "가을", lDeg: 90,  note: "은하면을 <b>옆으로</b> 보는 쪽" },
    { key: "winter", name: "겨울", lDeg: 180, note: "밤하늘이 은하 <b>바깥쪽</b>을 향한다" }
  ];

  global.Galaxy = {
    MW: MW, LY_PER_PC: LY_PER_PC,
    CLUSTERS: CLUSTERS, NEBULAE: NEBULAE, SEASONS: SEASONS,
    clamp: clamp, pcToLy: pcToLy,
    pathInDisk: pathInDisk, milkyBrightness: milkyBrightness,
    byKey: byKey
  };
})(window);
